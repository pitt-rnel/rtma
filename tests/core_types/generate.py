"""Generate core_types_test.cpp from pyrtma's core message definitions.

The test asserts, at compile time, that the C++ headers define everything
in pyrtma's core_defs YAML files with the same values and layouts, and, when
it runs, that CoreMessageSize() and CoreMessageHash() in
include/internal/CoreMessages.h give every core message type its size and
hash, and -1 and 0 for every other type below 100:

    core_types.h          rtma_core.yaml
    quick_logger_types.h  quick_logger.yaml
    data_logger_types.h   data_logger.yaml

Run this after changing either side, with the pyrtma whose definitions the
headers should match:

    python tests/core_types/generate.py

test_core_types.py checks that the committed file is current.
"""

from __future__ import annotations

import pathlib
import sys

from pyrtma.compilers.c99 import type_map
from pyrtma.parser import MDF, SDF, Field, NativeType, Parser, TypeAlias

HERE = pathlib.Path(__file__).resolve().parent
OUTPUT = HERE / "core_types_test.cpp"

# Message types up to this one are core types.
MAX_RTMA_MSG_TYPE = 99

# Each core definitions file, and the header that mirrors it.
HEADERS = {
    "rtma_core": "core_types.h",
    "quick_logger": "quick_logger_types.h",
    "data_logger": "data_logger_types.h",
}


def parse() -> Parser:
    import pyrtma.parser

    defs = pathlib.Path(pyrtma.parser.__file__).parent / "core_defs" / "rtma.defs"
    parser = Parser()
    parser.parse(defs)
    return parser


def c_type(obj: NativeType | TypeAlias | SDF | MDF) -> str:
    """The C++ name of a field's element type."""
    if isinstance(obj, NativeType):
        return type_map[obj.name]
    if isinstance(obj, TypeAlias):
        return obj.name
    if isinstance(obj, MDF):
        return f"MDF_{obj.name}"
    return obj.name


def struct_asserts(c_name: str, fields: list[Field], size: int) -> list[str]:
    out = [f"static_assert(sizeof({c_name}) == {size}, \"{c_name} size\");"]
    for f in fields:
        if f.padding:
            continue
        member = f"decltype({c_name}::{f.name})"
        where = f"{c_name}::{f.name}"
        out.append(
            f"static_assert(offsetof({c_name}, {f.name}) == {f.offset}, \"{where} offset\");"
        )
        out.append(
            f"static_assert(std::is_same<std::remove_all_extents<{member}>::type, "
            f"{c_type(f.type_obj)}>::value, \"{where} type\");"
        )
        rank = 1 if f.length else 0
        out.append(f"static_assert(std::rank<{member}>::value == {rank}, \"{where} rank\");")
        if f.length:
            out.append(
                f"static_assert(std::extent<{member}>::value == {f.length}, \"{where} length\");"
            )
    return out


def section(p: Parser, src: str) -> list[str]:
    def mine(objs):
        return [o for o in objs.values() if o.src.name == src]

    out = []
    for c in mine(p.constants):
        out.append(f"static_assert({c.name} == {c.value}, \"{c.name}\");")
    for a in mine(p.aliases):
        out.append(
            f"static_assert(std::is_same<{a.name}, {c_type(a.type_obj)}>::value, \"{a.name}\");"
        )
    for h in mine(p.host_ids):
        out.append(f"static_assert(HID_{h.name} == {h.value}, \"HID_{h.name}\");")
    for m in mine(p.module_ids):
        out.append(f"static_assert(MID_{m.name} == {m.value}, \"MID_{m.name}\");")
    for s in mine(p.struct_defs):
        out.append("")
        out += struct_asserts(s.name, s.fields, s.size)
    for m in mine(p.message_defs):
        out.append("")
        out.append(f"static_assert(MT_{m.name} == {m.type_id}, \"MT_{m.name}\");")
        out.append(f"static_assert(HASH_{m.name} == 0x{m.hash[:8]}u, \"HASH_{m.name}\");")
        if m.fields:
            out += struct_asserts(f"MDF_{m.name}", m.fields, m.size)
    return out


def generate() -> str:
    p = parse()
    lines = [
        "// Generated by tests/core_types/generate.py from pyrtma's core message",
        "// definitions. Do not edit; run the script again instead.",
        "//",
        "// Compiling this file checks that the C++ headers match the YAML files.",
        "",
        "#include <RTMA_types.h>",
        "",
        '#include "CoreMessages.h"',
        "",
        "#include <cstddef>",
        "#include <cstdio>",
        "#include <type_traits>",
    ]
    for src, header in HEADERS.items():
        lines += ["", f"// {header}: {src}.yaml", ""]
        lines += section(p, src)
    lines += ["", *main_function(p), ""]
    return "\n".join(lines)


def main_function(p: Parser) -> list[str]:
    """Check the core message tables, CoreMessageSize() and CoreMessageHash()."""
    core = {m.type_id: m for m in p.message_defs.values() if m.type_id <= MAX_RTMA_MSG_TYPE}
    out = [
        "static int failures = 0;",
        "",
        "static void check(int msg_type, int size, uint32_t hash) {",
        "  if (CoreMessageSize(msg_type) != size) {",
        '    std::printf("CoreMessageSize(%d) is %d, expected %d\\n", msg_type,',
        "                CoreMessageSize(msg_type), size);",
        "    ++failures;",
        "  }",
        "  if (CoreMessageHash(msg_type) != hash) {",
        '    std::printf("CoreMessageHash(%d) is 0x%08x, expected 0x%08x\\n", msg_type,',
        "                (unsigned)CoreMessageHash(msg_type), (unsigned)hash);",
        "    ++failures;",
        "  }",
        "}",
        "",
        "int main() {",
        "  // Every core message type, and -1 and 0 for every other type below 100.",
    ]
    for t in range(-1, MAX_RTMA_MSG_TYPE + 1):
        m = core.get(t)
        if m is None:
            out.append(f"  check({t}, -1, 0x00000000u);")
        else:
            out.append(f"  check({t}, {m.size}, 0x{m.hash[:8]}u);")
    out += ["  return failures == 0 ? 0 : 1;", "}"]
    return out


def main() -> int:
    OUTPUT.write_text(generate(), encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
